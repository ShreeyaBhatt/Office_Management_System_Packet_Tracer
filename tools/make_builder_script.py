"""Generate build_office_network.js from configs/ and web/index.html.

Paste the generated script into Packet Tracer's Builder Code Editor (PTBuilder
extension). Re-run this generator after changing any config or the web page.
"""
import json
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parent

IOS_DEVICES = ["R1-OMS", "SW-CORE", "SW-ACCOUNTS", "SW-HR", "SW-IT"]

# configureIosDevice enters global config mode and saves on its own.
SKIPPED_COMMANDS = {"enable", "configure terminal", "end", "write memory"}


def ios_commands(device):
    text = (ROOT / "configs" / f"{device}.txt").read_text(encoding="utf-8")
    lines = (line.strip() for line in text.splitlines())
    return "\n".join(l for l in lines if l and l not in SKIPPED_COMMANDS)


TEMPLATE = r"""// Office Management System: builds the README topology in Packet Tracer.
// GENERATED by tools/make_builder_script.py - edit configs/ or web/, not this file.
// Run on a NEW BLANK file: Extensions > Builder Code Editor > paste > Run.

var IOS_CONFIGS = __IOS_CONFIGS__;
var INDEX_HTML = __INDEX_HTML__;

var MASK = "255.255.255.0";
var SERVER_IP = "192.168.40.10";

var DEVICES = [
  ["R1-OMS", "2911", 400, 60],
  ["SW-CORE", "2960-24TT", 400, 180],
  ["SERVER0", "Server-PT", 620, 180],
  ["SW-ACCOUNTS", "2960-24TT", 150, 320],
  ["SW-HR", "2960-24TT", 400, 320],
  ["SW-IT", "2960-24TT", 650, 320],
  ["ACC-PC1", "PC-PT", 90, 460],
  ["ACC-PC2", "PC-PT", 210, 460],
  ["HR-PC1", "PC-PT", 340, 460],
  ["HR-PC2", "PC-PT", 460, 460],
  ["IT-PC1", "PC-PT", 590, 460],
  ["IT-PC2", "PC-PT", 710, 460]
];

var LINKS = [
  ["R1-OMS", "GigabitEthernet0/0", "SW-CORE", "GigabitEthernet0/1"],
  ["SW-CORE", "FastEthernet0/1", "SW-ACCOUNTS", "FastEthernet0/1"],
  ["SW-CORE", "FastEthernet0/2", "SW-HR", "FastEthernet0/1"],
  ["SW-CORE", "FastEthernet0/3", "SW-IT", "FastEthernet0/1"],
  ["SW-CORE", "FastEthernet0/4", "SERVER0", "FastEthernet0"],
  ["SW-ACCOUNTS", "FastEthernet0/2", "ACC-PC1", "FastEthernet0"],
  ["SW-ACCOUNTS", "FastEthernet0/3", "ACC-PC2", "FastEthernet0"],
  ["SW-HR", "FastEthernet0/2", "HR-PC1", "FastEthernet0"],
  ["SW-HR", "FastEthernet0/3", "HR-PC2", "FastEthernet0"],
  ["SW-IT", "FastEthernet0/2", "IT-PC1", "FastEthernet0"],
  ["SW-IT", "FastEthernet0/3", "IT-PC2", "FastEthernet0"]
];

var POOLS = [
  { name: "ACCOUNTS", network: "192.168.10.0", router: "192.168.10.1", start: "192.168.10.100", end: "192.168.10.149" },
  { name: "HR", network: "192.168.20.0", router: "192.168.20.1", start: "192.168.20.100", end: "192.168.20.149" },
  { name: "IT", network: "192.168.30.0", router: "192.168.30.1", start: "192.168.30.100", end: "192.168.30.149" }
];

var PCS = ["ACC-PC1", "ACC-PC2", "HR-PC1", "HR-PC2", "IT-PC1", "IT-PC2"];

var report = [];

function check(label, actual, expected) {
  if (String(actual) !== String(expected)) {
    report.push("CHECK " + label + ": got '" + actual + "', expected '" + expected + "'");
  }
}

// A failed service is reported, not fatal, so the others still get configured.
function service(label, configure) {
  try {
    configure();
    report.push("OK " + label);
  } catch (error) {
    report.push("FAILED " + label + " (use SERVER_SETUP.md): " + error);
  }
}

if (getDevices().length > 0) {
  throw new Error("Workspace is not empty. Use File > New, then run this again.");
}

DEVICES.forEach(function (d) {
  if (!addDevice(d[0], d[1], d[2], d[3])) {
    throw new Error("Could not add device " + d[0] + " (" + d[1] + ")");
  }
});
report.push("OK " + DEVICES.length + " devices");

LINKS.forEach(function (l) {
  if (!addLink(l[0], l[1], l[2], l[3], "straight")) {
    throw new Error("Could not link " + l.join(" "));
  }
});
report.push("OK " + LINKS.length + " links");

Object.keys(IOS_CONFIGS).forEach(function (name) {
  configureIosDevice(name, IOS_CONFIGS[name]);
});
report.push("OK IOS configs");

configurePcIp("SERVER0", false, SERVER_IP, MASK, "192.168.40.1", SERVER_IP);
report.push("OK SERVER0 address");

var server = ipc.network().getDevice("SERVER0");

service("DHCP pools", function () {
  var dhcp = server.getProcess("DhcpServerMainProcess").getDhcpServerProcessByPortName("FastEthernet0");
  dhcp.setEnable(true);
  POOLS.forEach(function (p) {
    dhcp.addPool(p.name);
    var pool = dhcp.getPool(p.name);
    pool.setNetworkMask(p.network, MASK);
    pool.setDefaultRouter(p.router);
    pool.setDnsServerIp(SERVER_IP);
    pool.setStartIp(p.start);
    pool.setEndIp(p.end);
    pool.setMaxUsers(50);
    check(p.name + " network", pool.getNetworkAddress(), p.network);
    check(p.name + " mask", pool.getSubnetMask(), MASK);
    check(p.name + " gateway", pool.getDefaultRouter(), p.router);
    check(p.name + " DNS", pool.getDnsServerIp(), SERVER_IP);
    check(p.name + " start", pool.getStartIp(), p.start);
    check(p.name + " max users", pool.getMaxUsers(), 50);
  });
  try {
    dhcp.removePool("serverPool");
    report.push(dhcp.getPool("serverPool") ? "NOTE serverPool could not be removed" : "OK serverPool removed");
  } catch (error) {
    report.push("NOTE serverPool could not be removed: " + error);
  }
});

service("DNS record", function () {
  var dns = server.getProcess("DnsServerProcess");
  dns.setEnable(true);
  dns.addARecordToNameServerDb("office.local", SERVER_IP);
  check("office.local", dns.getIpAddOfDomain("office.local"), SERVER_IP);
});

service("HTTP page", function () {
  var http = server.getProcess("HttpServer");
  http.setEnable(true);
  http.setPageContents("index.html", INDEX_HTML);
  check("index.html", http.getPage("index.html"), INDEX_HTML);
});

PCS.forEach(function (name) {
  configurePcIp(name, true);
});
report.push("OK PCs set to DHCP");

var summary = report.join("\n");
console.log(summary);
ipc.appWindow().showMessageBox("Office network build", "Build finished. Review, then File > Save As.", summary, 3, 0x00000400, 0x00000400, 0x00000400);
"""


def main():
    configs = {device: ios_commands(device) for device in IOS_DEVICES}
    with open(ROOT / "web" / "index.html", encoding="utf-8", newline="") as f:
        html = f.read()
    script = (
        TEMPLATE
        .replace("__IOS_CONFIGS__", json.dumps(configs, indent=2))
        .replace("__INDEX_HTML__", json.dumps(html))
    )
    output = TOOLS / "build_office_network.js"
    output.write_text(script, encoding="utf-8", newline="\n")
    print(f"Wrote {output}")


if __name__ == "__main__":
    main()
